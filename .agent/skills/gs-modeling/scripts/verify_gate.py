def write_json_nobom(path: Path, obj: dict):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2, ensure_ascii=False), encoding="utf-8")


def label_image(im: Image.Image, text: str) -> Image.Image:
    out = im.copy()
    d = ImageDraw.Draw(out)
    tw = min(out.width, max(180, len(text) * 7 + 20))
    d.rectangle([0, 0, tw, 26], fill=(20, 22, 28))
    d.text((8, 6), text, fill=(240, 240, 240))
    return out


def fit_square(im: Image.Image, size: int, bg=(38, 42, 54)) -> Image.Image:
    im = im.convert("RGB")
    w, h = im.size
    scale = min(size / max(w, 1), size / max(h, 1))
    nw, nh = max(1, int(round(w * scale))), max(1, int(round(h * scale)))
    res = im.resize((nw, nh), Image.Resampling.LANCZOS)
    canvas = Image.new("RGB", (size, size), bg)
    canvas.paste(res, ((size - nw) // 2, (size - nh) // 2))
    return canvas


def load_rgb_and_fg_mask(img_path: Path, bg_fill=(37, 32, 40)):
    """Load an image (RGBA or solid-bg RGB) and return (RGB Image, boolean fg mask)."""
    im = Image.open(img_path)
    if im.mode in ("RGBA", "LA") or ("transparency" in im.info):
        rgba = im.convert("RGBA")
        arr = np.asarray(rgba)
        if int((arr[:, :, 3] <= 20).sum()) >= 100:
            fg = arr[:, :, 3] > 20
            bg = Image.new("RGBA", rgba.size, (*bg_fill, 255))
            rgb_im = Image.alpha_composite(bg, rgba).convert("RGB")
            return rgb_im, fg
    rgb_im = im.convert("RGB")
    arr = np.asarray(rgb_im, dtype=np.float32)
    h, w, _ = arr.shape
    # Sample upper-left & upper-right corners (bust renders have shoulders at bottom corners!)
    corners = np.concatenate([
        arr[4:18, 4:18].reshape(-1, 3),
        arr[4:18, w - 18 : w - 4].reshape(-1, 3),
    ], axis=0)
    bg_col = np.median(corners, axis=0)
    fg = np.linalg.norm(arr - bg_col[None, None, :], axis=-1) > 16.0
    return rgb_im, fg


def fg_bbox(fg: np.ndarray):
    ys, xs = np.where(fg)
    if len(xs) < 20:
        return 0, 0, fg.shape[1], fg.shape[0]
    return int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1


def crop_head_by_neck(rgb: Image.Image, fg: np.ndarray) -> tuple[Image.Image, float]:
    """Data-driven head crop (top of head/hat -> deepest neck minimum) using row pixel count fg_count(y).

    Using fg_count(y) instead of xmax-xmin makes neck detection immune to thin accessories (monocle chains, hair wisps)
    and finds the exact neck minimum before shoulders/T-pose arms widen.
    """
    x0, y0, x1, y1 = fg_bbox(fg)
    h_tot = max(1, y1 - y0)
    fg_cnt = fg[y0:y1, :].sum(axis=1).astype(np.float32)

    k = max(3, int(h_tot * 0.015) | 1)
    w_sm = np.convolve(fg_cnt, np.ones(k, dtype=np.float32) / k, mode="same")

    # 1. Walk downward from top to find the FIRST clear head/hat peak (where w_sm descends significantly below peak)
    peak_idx = 0
    w_head = 0.0
    for dy in range(1, h_tot):
        if w_sm[dy] > w_head:
            w_head = float(w_sm[dy])
            peak_idx = dy
        elif w_head > 10.0 and w_sm[dy] < 0.72 * w_head and dy > max(12, int(h_tot * 0.05)):
            break

    # 2. Scan downward from peak_idx to find the deepest neck minimum BEFORE shoulders widen again
    min_w = w_head
    neck_idx = peak_idx
    found_narrow = False
    for dy in range(peak_idx + 1, h_tot):
        if w_sm[dy] < min_w:
            min_w = float(w_sm[dy])
            neck_idx = dy
        if min_w < 0.68 * w_head:
            found_narrow = True
        if found_narrow and (w_sm[dy] > max(min_w * 1.35, 0.78 * w_head) or w_sm[dy] > 1.15 * w_head):
            break

    # 3. Compute tight horizontal head bbox strictly from rows [y0 .. y0 + neck_idx]
    if neck_idx < max(20, int(h_tot * 0.25)):
        neck_idx = int(h_tot * 0.72)
    sub_fg = fg[y0 : y0 + neck_idx + 1, :]
    ys, xs = np.where(sub_fg)
    if len(xs) < 20:
        crop = rgb.crop((x0, y0, x1, y1))
        return crop, (y1 - y0) / max(float(x1 - x0), 1.0)
    hx0, hx1 = int(xs.min()), int(xs.max()) + 1
    hy0, hy1 = y0 + int(ys.min()), y0 + int(ys.max()) + 1
    hw, hh = max(1, hx1 - hx0), max(1, hy1 - hy0)
    pad = int(round(max(hw, hh) * 0.05))
    crop = rgb.crop((max(0, hx0 - pad), max(0, hy0 - pad), min(rgb.width, hx1 + pad), min(rgb.height, hy1 + pad)))
    return crop, hh / float(hw)


def crop_design_bust(img_path: Path, top_frac: float = 0.27) -> tuple[Image.Image, float]:
    """Data-driven head crop of the original design image (ignores T-pose arms/shoulders)."""
    rgb, fg = load_rgb_and_fg_mask(img_path)
    return crop_head_by_neck(rgb, fg)


def build_1to1_design_overlay(
    design_path: Path,
    render_path: Path,
    out_path: Path,
    is_bust: bool = False,
    bust_top_frac: float = 0.27,
    panel_size: int = 512,
) -> dict:
    """Create a 3-panel 1:1 comparison: Design | 3DGS Front | 50/50 Overlay, and measure vertical stretch."""
    des_rgb, des_fg = load_rgb_and_fg_mask(design_path)
    ren_rgb, ren_fg = load_rgb_and_fg_mask(render_path)

    if is_bust:
        des_crop, des_aspect = crop_head_by_neck(des_rgb, des_fg)
        ren_crop, ren_aspect = crop_head_by_neck(ren_rgb, ren_fg)
    else:
        dx0, dy0, dx1, dy1 = fg_bbox(des_fg)
        des_crop = des_rgb.crop((dx0, dy0, dx1, dy1))
        des_aspect = (dy1 - dy0) / max(float(dx1 - dx0), 1.0)
        rx0, ry0, rx1, ry1 = fg_bbox(ren_fg)
        ren_crop = ren_rgb.crop((rx0, ry0, rx1, ry1))
        ren_aspect = (ry1 - ry0) / max(float(rx1 - rx0), 1.0)

    ren_top_clipped = bool(int(ren_fg[0:2, :].sum()) >= 12)
    stretch_pct = (ren_aspect / max(des_aspect, 1e-4) - 1.0) * 100.0

    p_des = fit_square(des_crop, panel_size)
    p_ren = fit_square(ren_crop, panel_size)
    a_des = np.asarray(p_des, dtype=np.float32)
    a_ren = np.asarray(p_ren, dtype=np.float32)
    ov = np.clip(0.50 * a_des * np.array([0.85, 1.05, 1.10]) + 0.50 * a_ren * np.array([1.10, 0.98, 0.88]), 0, 255).astype(np.uint8)
    p_ov = Image.fromarray(ov)

    sheet = Image.new("RGB", (panel_size * 3, panel_size), (24, 26, 32))
    sheet.paste(label_image(p_des, f"1. Original Design (H/W={des_aspect:.2f})"), (0, 0))
    sheet.paste(label_image(p_ren, f"2. 3DGS Front (H/W={ren_aspect:.2f}){' [TOP CLIPPED]' if ren_top_clipped else ''}"), (panel_size, 0))
    sheet.paste(label_image(p_ov, f"3. 50/50 Overlay (stretch={stretch_pct:+.1f}%)"), (panel_size * 2, 0))
    out_path.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(out_path)

    return {
        "design_aspect_hw": round(float(des_aspect), 4),
        "render_aspect_hw": round(float(ren_aspect), 4),
        "vertical_stretch_pct": round(float(stretch_pct), 2),
        "render_top_clipped": ren_top_clipped,
        "overlay_image": str(out_path),
    }


def check_3d_floaters(xyz_opaque: np.ndarray, max_floater_ratio: float = 0.005) -> dict:
    """Detect isolated/floating splat outliers via 5th-nearest-neighbor spacing."""
    if len(xyz_opaque) < 50:
        return {"opaque_count": int(len(xyz_opaque)), "isolated_count": 0, "isolated_ratio": 0.0, "median_nn5": 0.0, "floater_flag": False}
    # Subsample deterministically if > 80k points for fast O(N log N) check
    if len(xyz_opaque) > 80000:
        step = max(1, len(xyz_opaque) // 80000)
        pts = xyz_opaque[::step]
    else:
        pts = xyz_opaque
    tree = cKDTree(pts)
    dists, _ = tree.query(pts, k=6)
    nn5 = dists[:, 5]
    med = float(np.median(nn5))
    thresh = max(0.008, med * 5.0)
    isolated = int((nn5 > thresh).sum())
    ratio = isolated / float(len(pts))
    return {
        "sampled_opaque_count": int(len(pts)),
        "median_nn5": round(med, 5),
        "outlier_threshold": round(thresh, 5),
        "isolated_count": isolated,
        "isolated_ratio": round(ratio, 5),
        "floater_flag": bool(ratio > max_floater_ratio),
    }


def run_gate1(args) -> int:
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    ply_path = Path(args.ply)
    data, _ = read_ply(ply_path)

    xyz = np.column_stack([data["x"], data["y"], data["z"]]).astype(np.float32)
    op = 1.0 / (1.0 + np.exp(-np.clip(data["opacity"], -20, 20)))
    nan_inf = int(sum(int((~np.isfinite(data[f])).sum()) for f in data.dtype.names))
    z_min, z_max = float(np.percentile(xyz[:, 2], 0.5)), float(np.percentile(xyz[:, 2], 99.5))
    height = z_max - z_min

    failures = []
    if nan_inf > 0:
        failures.append(f"nan_or_inf_total={nan_inf} > 0")
    if len(data) < 10000:
        failures.append(f"splat_count={len(data)} < 10000")
    if not (0.75 <= height <= 1.25):
        failures.append(f"normalized_height={height:.3f} outside [0.75, 1.25]")

    floater_stats = check_3d_floaters(xyz[op > 0.15])
    if floater_stats["floater_flag"]:
        failures.append(
            f"Excessive 3D isolated floaters: {floater_stats['isolated_count']} pts "
            f"({floater_stats['isolated_ratio']*100:.2f}% > 0.50%)"
        )

    # Side-view (90 deg) posture: trunk lean and sole tilt. Measured BEFORE any render review,
    # because a leaning body is easy to miss in front views (snowdrop: 17 deg back lean passed visually).
    cfg = json.loads(Path(args.config).read_text(encoding="utf-8")) if args.config else {}
    qa_cfg = cfg.get("qa_thresholds", {})
    max_lean = float(qa_cfg.get("max_trunk_lean_deg", args.max_lean_deg))
    max_sole = float(qa_cfg.get("max_sole_tilt_deg", args.max_sole_tilt_deg))
    xyz_op = xyz[op > 0.15].astype(np.float64)
    lean = trunk_lean_deg(xyz_op)
    sole = sole_tilt_deg(xyz_op)
    posture = {"trunk_lean_deg": round(lean, 2), "sole_tilt_deg": round(sole, 2),
               "max_trunk_lean_deg": max_lean, "max_sole_tilt_deg": max_sole,
               "sign": "+ = top leans back (+Y), - = forward"}
    if np.isfinite(lean) and abs(lean) > max_lean:
        failures.append(f"Side-view trunk lean {lean:+.1f} deg exceeds +/-{max_lean:.1f} deg (fix posture before visual review)")
    if np.isfinite(sole) and abs(sole) > max_sole:
        failures.append(f"Sole tilt {sole:+.1f} deg exceeds +/-{max_sole:.1f} deg (soles not level in side view)")

    # Build standardized Gate 1 evidence sheet (Design Reference | 3DGS 4-View)
    evidence_path = out_dir / "gate1_evidence_sheet.png"
    if args.design and args.render_4view:
        im_des = label_image(fit_square(Image.open(args.design), 768), "Design Reference (Original)")
        im_4v = label_image(fit_square(Image.open(args.render_4view), 768), "Gate 1 3DGS Render (0/45/90/180)")
        sheet = Image.new("RGB", (1536, 768), (30, 33, 40))
        sheet.paste(im_des, (0, 0))
        sheet.paste(im_4v, (768, 0))
        sheet.save(evidence_path)
    else:
        failures.append("Missing --design or --render-4view for standardized Gate 1 evidence sheet")

    # Optional 1:1 Design vs Front Render aspect-ratio & overlay check
    design_match = None
    if args.design and args.render_front and Path(args.render_front).exists():
        design_match = build_1to1_design_overlay(
            Path(args.design),
            Path(args.render_front),
            out_dir / "gate1_design_1to1_overlay.png",
            is_bust=False,
        )
        if design_match.get("render_top_clipped"):
            failures.append("Gate 2 render_front is top-clipped (hat/head cut off at y=0 — pull camera back for accurate 1:1 proportion check)")
        max_stretch = float(args.max_stretch_pct)
        if abs(design_match["vertical_stretch_pct"]) > max_stretch:
            failures.append(
                f"Design proportion mismatch (stretch/squash): {design_match['vertical_stretch_pct']:+.1f}% "
                f"(exceeds +/-{max_stretch:.1f}% tolerance)"
            )

    report = {
        "validator": "verify_gate.py",
        "validator_version": VALIDATOR_VERSION,
        "gate": "Gate 1 (Static 3DGS Quality, Cleanup & Design Consistency)",
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "inputs": {
            "ply": str(ply_path),
            "design": str(args.design),
            "render_4view": str(args.render_4view),
            "render_front": str(args.render_front) if args.render_front else None,
        },
        "metrics": {
            "num_gaussians": int(len(data)),
            "opaque_gaussians_gt_0p1": int((op > 0.1).sum()),
            "nan_or_inf_total": nan_inf,
            "height_span": round(height, 4),
            "floaters": floater_stats,
            "posture_side_view": posture,
            "design_1to1_match": design_match,
        },
        "evidence_image": str(evidence_path) if evidence_path.exists() else None,
        "overlay_image": design_match["overlay_image"] if design_match else None,
        "failures": failures,
        "numeric_gate": "OK (awaiting_independent_visual_review)" if not failures else "FAIL (hard_stop)",
    }
    write_json_nobom(out_dir / "gate1_verify_report.json", report)
    print(json.dumps(report, indent=2, ensure_ascii=False))
    return 0 if not failures else 1


def run_gate2(args) -> int:
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    failures = []

    for req_name, req_val in [("design", args.design), ("before_face", args.before_face), ("after_sheet", args.after_sheet)]:
        if not req_val or not Path(req_val).exists():
            failures.append(f"Missing required Gate 2 evidence input: --{req_name.replace('_', '-')}")

    # Optional 3D floater check on Gate 2 PLY
    floater_stats = None
    if args.ply and Path(args.ply).exists():
        data, _ = read_ply(Path(args.ply))
        xyz = np.column_stack([data["x"], data["y"], data["z"]]).astype(np.float32)
        op = 1.0 / (1.0 + np.exp(-np.clip(data["opacity"], -20, 20)))
        floater_stats = check_3d_floaters(xyz[op > 0.15])
        if floater_stats["floater_flag"]:
            failures.append(
                f"Gate 2 excessive 3D isolated floaters: {floater_stats['isolated_count']} pts "
                f"({floater_stats['isolated_ratio']*100:.2f}% > 0.50%)"
            )

    # Mandatory/Standard 1:1 Bust Design vs 3DGS Overlay (anti-stretch + full bust cleanup visibility)
    design_match = None
    bust_front_src = args.render_front if (args.render_front and Path(args.render_front).exists()) else args.before_face
    if args.design and bust_front_src and Path(args.design).exists() and Path(bust_front_src).exists():
        design_match = build_1to1_design_overlay(
            Path(args.design),
            Path(bust_front_src),
            out_dir / "gate2_design_bust_1to1_overlay.png",
            is_bust=True,
            bust_top_frac=float(args.bust_top_frac),
        )
        if design_match.get("render_top_clipped"):
            failures.append("Gate 2 render_front is top-clipped (hat/head cut off at y=0 — pull camera back for accurate 1:1 proportion check)")
        max_stretch = float(args.max_stretch_pct)
        if abs(design_match["vertical_stretch_pct"]) > max_stretch:
            failures.append(
                f"Bust/Head proportion mismatch vs design: {design_match['vertical_stretch_pct']:+.1f}% "
                f"(exceeds +/-{max_stretch:.1f}% tolerance — check vertical stretch/aspect ratio!)"
            )

    evidence_path = out_dir / "gate2_evidence_sheet.png"
    if not any(f.startswith("Missing required Gate 2") for f in failures):
        # Auto-crop bust from original design so it's 1:1 comparable (not tiny full-body!)
        des_bust, _ = crop_design_bust(Path(args.design), top_frac=float(args.bust_top_frac))
        im_des = label_image(fit_square(des_bust, 480), "1. Original Design (Bust 1:1)")
        im_bef = label_image(fit_square(Image.open(args.before_face), 480), "2. Gate 1 Static Face (BEFORE)")
        im_aft = Image.open(args.after_sheet).convert("RGB")
        aw, ah = im_aft.size
        target_w = 1440
        target_h = max(360, int(round(ah * (target_w / max(aw, 1)))))
        im_aft_res = label_image(im_aft.resize((target_w, target_h), Image.Resampling.LANCZOS), "3. Gate 2 Dynamic Eyes & Eyelids (AFTER - Must match Design & NOT degrade)")

        top_h = 480
        sheet = Image.new("RGB", (target_w, top_h + target_h), (28, 31, 38))
        sheet.paste(im_des, (120, 0))
        sheet.paste(im_bef, (840, 0))
        sheet.paste(im_aft_res, (0, top_h))
        sheet.save(evidence_path)

    report = {
        "validator": "verify_gate.py",
        "validator_version": VALIDATOR_VERSION,
        "gate": "Gate 2 (Dynamic Doll Eyes, Bust Cleanup & Design Consistency)",
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "inputs": {
            "design": str(args.design),
            "before_face": str(args.before_face),
            "after_sheet": str(args.after_sheet),
            "render_front": str(args.render_front) if args.render_front else None,
            "ply": str(args.ply) if args.ply else None,
        },
        "metrics": {
            "floaters": floater_stats,
            "design_bust_1to1_match": design_match,
        },
        "evidence_image": str(evidence_path) if evidence_path.exists() else None,
        "overlay_image": design_match["overlay_image"] if design_match else None,
        "failures": failures,
        "numeric_gate": "OK (awaiting_independent_visual_review)" if not failures else "FAIL (hard_stop)",
    }
    write_json_nobom(out_dir / "gate2_verify_report.json", report)
    print(json.dumps(report, indent=2, ensure_ascii=False))
    return 0 if not failures else 1


def check_skeleton_anatomy(xyz_opaque: np.ndarray, skel: dict, max_bone_dev: float, max_protrusion: float) -> dict:
    """Bone-count-agnostic anatomical check on ALL bones in rig_skeleton.json against actual 3DGS point cloud."""
    bones = skel.get("bones", {})
    tree = cKDTree(xyz_opaque)

    roots = [k for k, v in bones.items() if v.get("parent") is None]
    missing_parents = [
        f"{k} -> missing parent '{v.get('parent')}'"
        for k, v in bones.items()
        if v.get("parent") is not None and v.get("parent") not in bones
    ]

    bone_metrics = {}
    protruding_bones = []
    high_dev_bones = []

    for bname, b in bones.items():
        if bname == "root" or bname.startswith("eye_"):
            continue
        h = np.asarray(b["head"], dtype=np.float32)
        t = np.asarray(b["tail"], dtype=np.float32)
        if not (np.all(np.isfinite(h)) and np.all(np.isfinite(t))):
            protruding_bones.append(f"{bname}: NaN/Inf coordinates")
            continue
        dv = t - h
        blen = float(np.linalg.norm(dv))
        if blen < 1e-5:
            continue
        axis = dv / blen

        sample_ts = [0.0, 0.25, 0.50, 0.75, 1.0]
        worst_prot = 0.0
        worst_dev = 0.0
        worst_nn = 0.0

        slab_h = max(0.014, min(0.030, blen * 0.18))
        is_central_torso = (abs(float(h[0])) < 0.06 and abs(float(t[0])) < 0.06 and float(min(h[2], t[2])) > 0.35) or bname.startswith("clavicle_")
        perp_r = 0.135 if is_central_torso else 0.085

        for st in sample_ts:
            p = h + st * dv
            d_nn, _ = tree.query(p, k=1)
            worst_nn = max(worst_nn, float(d_nn))

            idx = tree.query_ball_point(p, r=perp_r)
            if len(idx) < 12:
                worst_prot = max(worst_prot, float(d_nn))
                worst_dev = max(worst_dev, float(d_nn))
                continue

            pts = xyz_opaque[idx]
            rel = pts - p[None, :]
            along = rel @ axis
            slab_m = np.abs(along) <= slab_h
            spts = pts[slab_m] if int(slab_m.sum()) >= 10 else pts

            lo = np.percentile(spts, 2, axis=0)
            hi = np.percentile(spts, 98, axis=0)
            prot_vec = np.maximum(0.0, np.maximum(lo - p, p - hi))
            prot = float(np.linalg.norm(prot_vec))
            worst_prot = max(worst_prot, prot)

            if 0.15 <= st <= 0.85:
                p05 = np.percentile(spts, 5, axis=0)
                p95 = np.percentile(spts, 95, axis=0)
                med = np.median(spts, axis=0)
                mid = 0.5 * (p05 + p95)
                centroid = np.where((p95 - p05) > 0.11, mid, med)
                c_rel = p - centroid
                c_perp = c_rel - float(np.dot(c_rel, axis)) * axis
                dev = float(np.linalg.norm(c_perp))
                worst_dev = max(worst_dev, dev)

        bone_metrics[bname] = {
            "length": round(blen, 4),
            "max_protrusion": round(worst_prot, 5),
            "max_centroid_dev": round(worst_dev, 5),
            "max_nn_dist": round(worst_nn, 5),
        }
        if worst_prot > max_protrusion:
            protruding_bones.append(f"{bname} (protrusion={worst_prot:.4f} > {max_protrusion:.4f})")
        is_non_cylindrical = bname.startswith("clavicle_") or bname.startswith("foot_")
        if (not is_non_cylindrical) and worst_dev > max_bone_dev:
            high_dev_bones.append(f"{bname} (centroid_dev={worst_dev:.4f} > {max_bone_dev:.4f})")

    sym_pairs = {}
    sym_failures = []
    for bname in sorted(bones.keys()):
        if bname.endswith("_L"):
            rname = bname[:-2] + "_R"
            if rname in bones:
                hL, tL = np.asarray(bones[bname]["head"], float), np.asarray(bones[bname]["tail"], float)
                hR, tR = np.asarray(bones[rname]["head"], float), np.asarray(bones[rname]["tail"], float)
                dz = float(abs(hL[2] - hR[2]) + abs(tL[2] - tR[2])) * 0.5
                dy = float(abs(hL[1] - hR[1]) + abs(tL[1] - tR[1])) * 0.5
                dlen = float(abs(np.linalg.norm(tL - hL) - np.linalg.norm(tR - hR)))
                sym_pairs[bname[:-2]] = {"dz": round(dz, 5), "dy": round(dy, 5), "dlen": round(dlen, 5)}
                if dz > 0.012 or dy > 0.015 or dlen > 0.018:
                    sym_failures.append(f"{bname[:-2]}_L/R (dz={dz:.4f}, dy={dy:.4f}, dlen={dlen:.4f})")

    return {
        "total_bones": len(bones),
        "roots": roots,
        "missing_parents": missing_parents,
        "bone_metrics": bone_metrics,
        "protruding_bones": protruding_bones,
        "high_centroid_dev_bones": high_dev_bones,
        "lr_symmetry": sym_pairs,
        "lr_symmetry_failures": sym_failures,
    }


def run_gate3(args) -> int:
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    pkg_dir = Path(args.pkg_dir)
    cfg = json.loads(Path(args.config).read_text(encoding="utf-8")) if args.config else {}
    th = cfg.get("qa_thresholds", {})
    max_bone_dev = float(th.get("max_bone_deviation", 0.018))
    max_protrusion = float(th.get("max_bone_protrusion", 0.004))

    failures = []
    ply_path = pkg_dir / "master.ply"
    skel_path = pkg_dir / "rig_skeleton.json"
    if not ply_path.exists() or not skel_path.exists():
        failures.append(f"Missing master.ply or rig_skeleton.json in {pkg_dir}")
        report = {
            "validator": "verify_gate.py",
            "validator_version": VALIDATOR_VERSION,
            "gate": "Gate 3 (Anatomical Skeleton & Full-Body Rig)",
            "failures": failures,
            "numeric_gate": "FAIL (hard_stop)",
        }
        write_json_nobom(out_dir / "gate3_verify_report.json", report)
        print(json.dumps(report, indent=2, ensure_ascii=False))
        return 1

    data, _ = read_ply(ply_path)
    skel = json.loads(skel_path.read_text(encoding="utf-8"))
    xyz = np.column_stack([data["x"], data["y"], data["z"]]).astype(np.float32)
    op = 1.0 / (1.0 + np.exp(-np.clip(data["opacity"], -20, 20)))
    xyz_opaque = xyz[op > 0.15]

    anat = check_skeleton_anatomy(xyz_opaque, skel, max_bone_dev=max_bone_dev, max_protrusion=max_protrusion)
    if len(anat["roots"]) != 1:
        failures.append(f"Expected 1 root bone, found {anat['roots']}")
    if anat["missing_parents"]:
        failures.extend(anat["missing_parents"])
    if anat["protruding_bones"]:
        failures.append("Bones protruding outside 3DGS body: " + "; ".join(anat["protruding_bones"]))
    if anat["high_centroid_dev_bones"]:
        failures.append("Bones exceeding max_bone_deviation from 3DGS cross-section centroid: " + "; ".join(anat["high_centroid_dev_bones"]))
    if anat["lr_symmetry_failures"]:
        failures.append("L/R bone asymmetry: " + "; ".join(anat["lr_symmetry_failures"]))

    blender_exe = Path(args.blender) if args.blender else DEFAULT_BLENDER
    xray_out = out_dir / "gate3_rig_xray_3view.png"
    if blender_exe.exists():
        subprocess.run(
            [str(blender_exe), "-b", "--python", str(SKILL_SCRIPTS / "render_rig_preview_blender.py"), "--", str(pkg_dir), str(xray_out)],
            check=True,
        )
        shutil.copy2(xray_out, pkg_dir / "preview_rig.png")
    else:
        failures.append(f"Blender not found at {blender_exe}; cannot render mandatory X-ray 3-view rig preview")

    report = {
        "validator": "verify_gate.py",
        "validator_version": VALIDATOR_VERSION,
        "gate": "Gate 3 (Anatomical Skeleton & Full-Body Rig)",
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "pkg_dir": str(pkg_dir),
        "thresholds": {"max_bone_deviation": max_bone_dev, "max_bone_protrusion": max_protrusion},
        "anatomy": anat,
        "evidence_images": {
            "rig_xray_3view": str(xray_out) if xray_out.exists() else None,
            "pose_sheet": str(args.pose_sheet) if args.pose_sheet else None,
        },
        "failures": failures,
        "numeric_gate": "OK (awaiting_independent_visual_review)" if not failures else "FAIL (hard_stop)",
    }
    write_json_nobom(out_dir / "gate3_verify_report.json", report)
    print(json.dumps(report, indent=2, ensure_ascii=False))
    return 0 if not failures else 1


def run_gate4(args) -> int:
    """Gate 4 Mechanical Video Validator: catches clipped heads/arms, too-fast segments, skipped Gate 2, and exports frame-0 vs design."""
    import imageio.v3 as iio

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    failures = []

    video_path = Path(args.video) if args.video else None
    if not video_path or not video_path.exists():
        failures.append(f"Missing --video MP4 file: {video_path}")
        report = {"validator": "verify_gate.py", "validator_version": VALIDATOR_VERSION, "gate": "Gate 4 (Video Mechanical QA)", "failures": failures, "numeric_gate": "FAIL (hard_stop)"}
        write_json_nobom(out_dir / "gate4_verify_report.json", report)
        print(json.dumps(report, indent=2, ensure_ascii=False))
        return 1

    if not args.allow_missing_prior_gates:
        for g in (2, 3):
            rp = out_dir / f"gate{g}_verify_report.json"
            if not rp.exists():
                failures.append(f"Procedure violation: missing prior {rp.name} (cannot skip Gate {g} before Gate 4 video!)")
            else:
                rj = json.loads(rp.read_text(encoding="utf-8"))
                if not str(rj.get("numeric_gate", "")).startswith("OK"):
                    failures.append(f"Prior Gate {g} did not pass numeric_gate: {rj.get('numeric_gate')}")

    meta = iio.immeta(video_path)
    fps = float(meta.get("fps", 12.0))
    frames = iio.imread(video_path)
    n_frames, H, W, _ = frames.shape
    duration_sec = n_frames / max(fps, 1e-3)
    num_segments = max(1, int(args.num_segments))
    avg_seg_sec = duration_sec / num_segments
    min_seg_sec = float(args.min_seg_sec)

    if avg_seg_sec < min_seg_sec:
        failures.append(f"Video too fast: {duration_sec:.2f}s / {num_segments} segments = {avg_seg_sec:.2f}s/seg (< {min_seg_sec:.2f}s minimum)")

    banner_h = int(args.banner_height)
    top_clipped_frames = []
    for fi in range(n_frames):
        fr = frames[fi].astype(np.float32)
        c_tl = np.median(fr[banner_h + 6 : banner_h + 24, 6:24], axis=(0, 1))
        c_tr = np.median(fr[banner_h + 6 : banner_h + 24, W - 24 : W - 6], axis=(0, 1))
        bg = 0.5 * (c_tl + c_tr)
        top_strip = fr[banner_h + 1 : banner_h + 4, 8 : W - 8]
        fg_top = int((np.linalg.norm(top_strip - bg[None, None, :], axis=-1) > 28.0).sum())
        if fg_top >= 15:
            top_clipped_frames.append({"frame": fi, "fg_px": fg_top})

    if top_clipped_frames:
        sample_f = [x["frame"] for x in top_clipped_frames[:8]]
        failures.append(f"Top-border clipping (head/hand cropped) on {len(top_clipped_frames)}/{n_frames} frames (e.g. frames {sample_f})")

    ev_f0 = out_dir / "gate4_frame0_fullres.png"
    Image.fromarray(frames[0]).save(ev_f0)

    design_match = None
    if args.design and Path(args.design).exists():
        # Strip top banner before comparing frame 0 to design
        f0_nobanner = out_dir / "_tmp_frame0_nobanner.png"
        Image.fromarray(frames[0][banner_h:, :, :]).save(f0_nobanner)
        design_match = build_1to1_design_overlay(
            Path(args.design),
            f0_nobanner,
            out_dir / "gate4_frame0_vs_design_overlay.png",
            is_bust=bool(args.is_bust_video),
            bust_top_frac=float(args.bust_top_frac),
        )
        f0_nobanner.unlink(missing_ok=True)
        if design_match and float(design_match.get("render_aspect_hw", 0.0)) < 0.05:
            failures.append(
                f"Gate 4 Frame 0 foreground detection failed (render_aspect_hw={design_match.get('render_aspect_hw')}); "
                "cannot verify 1:1 consistency against design."
            )

    report = {
        "validator": "verify_gate.py",
        "validator_version": VALIDATOR_VERSION,
        "gate": "Gate 4 (Video Mechanical QA)",
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "video": str(video_path),
        "video_stats": {
            "n_frames": int(n_frames),
            "fps": round(fps, 2),
            "resolution": [int(W), int(H)],
            "duration_sec": round(duration_sec, 2),
            "num_segments": num_segments,
            "avg_sec_per_segment": round(avg_seg_sec, 2),
            "top_clipped_frame_count": len(top_clipped_frames),
        },
        "design_frame0_match": design_match,
        "evidence": {
            "mp4_for_direct_blind_qa": str(video_path),
            "frame0_fullres": str(ev_f0),
            "frame0_vs_design_overlay": design_match["overlay_image"] if design_match else None,
        },
        "failures": failures,
        "numeric_gate": "OK (awaiting_direct_mp4_blind_visual_review)" if not failures else "FAIL (hard_stop)",
    }
    write_json_nobom(out_dir / "gate4_verify_report.json", report)
    print(json.dumps(report, indent=2, ensure_ascii=False))
    return 0 if not failures else 1


