"""Official Immutable Gate Validator (verify_gate.py v3.0) for 3dgs-hybrid-doll-pipeline.

Design principles:
1. Single immutable validator for Gate 1, Gate 2, Gate 3, and Gate 4 (Maker agents must NEVER bypass or rewrite this).
2. Zero hardcoded bone counts, bone names, or character proportions:
   - Dynamically validates ALL bones present in rig_skeleton.json against master.ply.
   - Auto-discovers all _L / _R symmetric bone pairs.
3. Two-layer verification contract:
   - Layer 1 (this script): Deterministic math/geometry/proportion gates:
       * Gate 1: NaN/Inf, splat count, normalized height, 3D isolated-floater detection,
                 side-view trunk lean & sole tilt,
                 1:1 Design vs 3DGS front aspect-ratio (anti-stretch) & silhouette overlay.
       * Gate 2: 1:1 Bust Design vs 3DGS proportion/anti-stretch check & 50/50 overlay,
                 3D floater check, Before/After eye regression sheet (bust-cropped design).
       * Gate 3: All-bone containment (protrusion), cross-section centroid deviation,
                 auto L/R symmetry, tree connectivity, X-ray 3-view Blender render.
       * Gate 4: Prior Gate 2/3 enforcement, video pacing/duration, top-border clipping scan,
                 full-res frame-0 vs design reference export.
   - Layer 2 (Independent QA Reviewer): Visual/semantic judgment strictly on the standardized
     evidence sheets + 1:1 design overlays + .mp4 generated by this script.
   - This script NEVER outputs final PASS; it outputs "OK (awaiting_independent_visual_review)" or "FAIL (hard_stop)".
"""
